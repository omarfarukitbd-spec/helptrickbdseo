def detect_is_math(ans_text: str, q_text: str) -> bool:
    content = (ans_text + " " + q_text).lower()
    math_signals = ["journal", "ledger", "trial balance", "debit", "credit", "tk.", "tk", "shares", "bond", "balance sheet", "income statement", "dr.", "cr.", "জাবেদা", "খতিয়ান", "উদ্বৃত্ত পত্র", "গাণিতিক", "টাকা"]
    count = sum(1 for sig in math_signals if sig in content)
    return count >= 2 or "|" in ans_text or "1." in ans_text and "tk" in content

def get_topic_enrichment(q_text: str, tags: list, ans_text: str, is_math: bool):
    full_text = (q_text + " " + " ".join(tags) + " " + ans_text[:400]).lower()
    
    for rule in TOPIC_RULES:
        for kw in rule["keywords"]:
            if kw in full_text:
                intro = rule["intro_math"] if is_math else rule["intro_theory"]
                concl = rule["conclusion_math"] if is_math else rule["conclusion_theory"]
                return intro, concl
                
    intro = GENERIC_MATH_INTRO if is_math else GENERIC_THEORY_INTRO
    concl = GENERIC_MATH_CONCL if is_math else GENERIC_THEORY_CONCL
    return intro, concl

